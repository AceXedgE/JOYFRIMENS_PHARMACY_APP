import { test, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';

test('mobile receiving, interrupted dispatch retry, and direct shelf transfers in both directions', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByLabel('Username', { exact: true }).fill('test.admin');
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByLabel('Active shop')).toHaveValue(/.+/);
  await page.getByLabel('Active shop').selectOption({ label: 'Tomjoy Pharmacy' });
  const me = await (await page.request.get('/api/auth/me')).json();
  const shops = (await (await page.request.get('/api/shops')).json()).shops;
  const shopId = shops.find((s: { name: string }) => s.name === 'Tomjoy Pharmacy').id;
  const headers = { 'x-requested-with': 'joyfrimens', 'x-csrf-token': me.csrfToken };
  const product = await page.request.post(`/api/shops/${shopId}/catalogue`, { headers, data: { name: 'Mobile Stock Drug', genericName: 'Mobile Stock Drug', strength: '250 mg', dosageForm: 'Tablet', baseUnit: 'tablet', reason: 'Mobile inventory verification', units: [{ label: 'tablet', baseQuantity: 1, barcode: '', priceMinor: 100 }, { label: 'carton', baseQuantity: 100, barcode: '', priceMinor: 9000 }] } });
  expect(product.status()).toBe(201);
  const second = await page.request.post('/api/shops/' + shopId + '/catalogue', { headers, data: { name: 'Second Receipt Drug', genericName: 'Test generic', strength: '10 mg', dosageForm: 'Tablet', baseUnit: 'tablet', reason: 'Multi drug mobile receipt', units: [{ label: 'tablet', baseQuantity: 1, barcode: '', priceMinor: 100 }] } });
  expect(second.status()).toBe(201);
  await page.getByRole('button', { name: 'Stock & transfers', exact: true }).click();
  await page.getByRole('button', { name: 'Receive supplier delivery', exact: true }).click();
  const delivery = page.getByRole('region', { name: 'Supplier receipt editor' });
  await delivery.getByLabel('Drug and pack').selectOption({ label: 'Mobile Stock Drug · 250 mg · Tablet · carton (100 tablet)' });
  await delivery.getByLabel('Supplier', { exact: true }).fill('Mobile Supplier');
  await delivery.getByLabel('Delivery reference').fill('MOBILE-001');
  await delivery.getByLabel('Receipt notes').fill('Checked all drugs against one supplier document');
  await delivery.getByLabel('Batch number').fill('MOBILE-BATCH');
  await delivery.getByLabel('Expiry date').fill('2099-12-31');
  await delivery.getByLabel('Supplier quantity (packs)').fill('3');
  await delivery.getByLabel('Actually received (packs)').fill('2');
  await delivery.getByLabel('Allocation 1 base units').fill('150');
  await delivery.getByRole('button', { name: 'Split across another location' }).click();
  await delivery.getByLabel('Allocation 2 location').selectOption({ label: 'Tomjoy Pharmacy storeroom' });
  await delivery.getByLabel('Allocation 2 base units').fill('50');
  await delivery.getByLabel('Reason / delivery notes').fill('One carton missing; counted two cartons and split across shelf and store');
  await delivery.getByRole('button', { name: 'Save drug line' }).click();
  await delivery.getByRole('button', { name: 'Add another drug' }).click();
  await delivery.getByLabel('Find a drug').fill('Second Receipt');
  await delivery.getByLabel('Drug and pack').selectOption({ label: 'Second Receipt Drug · 10 mg · Tablet · tablet (1 tablet)' });
  await delivery.getByLabel('Batch number').fill('SECOND-LOT');
  await delivery.getByLabel('Expiry date').fill('2099-12-31');
  await delivery.getByLabel('Supplier quantity (packs)').fill('10');
  await delivery.getByLabel('Actually received (packs)').fill('10');
  await delivery.getByLabel('Allocation 1 base units').fill('10');
  await delivery.getByLabel('Reason / delivery notes').fill('All ten units received');
  await delivery.getByRole('button', { name: 'Save drug line' }).click();
  await delivery.getByRole('button', { name: 'Edit line 2' }).click();
  await expect(delivery.getByLabel('Batch number')).toHaveValue('SECOND-LOT');
  await delivery.getByRole('button', { name: 'Save drug line' }).click();
  await delivery.getByRole('button', { name: 'Review receipt' }).click();
  await expect(delivery.getByRole('heading', { name: 'Review complete receipt · 2' })).toBeVisible();
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await delivery.screenshot({ path: testInfo.outputPath('supplier-receipt-review.png') });
  await delivery.getByRole('button', { name: 'Confirm entire receipt' }).click();
  const shelfCard = page.locator('article').filter({ has: page.getByRole('button', { name: 'Transfer or count' }) }).filter({ hasText: 'Mobile Stock Drug' });
  await expect(shelfCard).toContainText('150 tablet(s)');
  await expect(page.getByText('Supplier quantity: 300; received: 200 base units.')).toBeVisible();
  await page.getByRole('button', { name: 'Open supplier receipt', exact: true }).click();
  await expect(page.getByText('2 drug / batch lines', { exact: false })).toBeVisible();
  await page.getByLabel('Approval notes').fill('Checked supplier document and noted missing carton');
  await page.getByRole('button', { name: 'Approve delivery record' }).click();
  await expect(page.getByRole('status')).toContainText('Complete supplier receipt approval');
  await page.getByRole('button', { name: 'Open supplier receipt', exact: true }).click();
  await expect(page.getByText(/Reviewed and approved by Test Administrator/).first()).toBeVisible();
  await shelfCard.getByRole('button', { name: 'Transfer or count' }).click();
  let transferForm = page.locator('form').filter({ has: page.getByRole('button', { name: 'Dispatch stock', exact: true }) });
  await transferForm.getByRole('combobox', { name: 'Destination', exact: true }).selectOption({ label: 'Joyfrimens Pharmacy shelf' });
  await transferForm.getByLabel('Dispatch quantity (tablet)').fill('40');
  await transferForm.getByLabel('Reason / delivery notes').fill('Direct shelf supply to Joyfrimens');
  // Server commits successfully, but the phone loses the response. The same request key
  // survives a page reload and must return the original result without a second dispatch.
  await page.route('**/api/inventory/transfers', async route => {
    await route.fetch(); await route.abort('failed');
  }, { times: 1 });
  await transferForm.getByRole('button', { name: 'Dispatch stock', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Retry pending request' })).toBeEnabled();
  await page.reload();
  await page.getByRole('button', { name: 'Stock & transfers', exact: true }).click();
  await page.getByRole('button', { name: 'Retry pending request' }).click();
  await expect(shelfCard).toContainText('110 tablet(s)');
  await expect(page.getByText('40 tablet(s) in transit')).toHaveCount(1);
  await page.getByRole('combobox', { name: 'Stock location', exact: true }).selectOption({ label: 'Tomjoy Pharmacy storeroom' });
  await expect(shelfCard).toContainText('50 tablet(s)');
  await page.getByLabel('Active shop').selectOption({ label: 'Joyfrimens Pharmacy' });
  const incoming = page.locator('article').filter({ has: page.getByRole('button', { name: 'Confirm receipt', exact: true }) });
  await incoming.getByLabel('Actually received now (tablet)').fill('35');
  await incoming.getByLabel('Reason / delivery notes').fill('Thirty five counted, five missing');
  await incoming.getByRole('button', { name: 'Confirm receipt', exact: true }).click();
  await expect(shelfCard).toContainText('35 tablet(s)');
  await expect(page.getByText('5 tablet(s) in transit')).toBeVisible();
  await incoming.getByRole('button', { name: 'View transfer history' }).click();
  await expect(incoming.getByText('5 outstanding at this receipt.')).toBeVisible();
  await incoming.getByLabel('Actually received now (tablet)').fill('5');
  await incoming.getByLabel('Reason / delivery notes').fill('Remaining five found and counted');
  await incoming.getByRole('button', { name: 'Confirm receipt', exact: true }).click();
  await expect(shelfCard).toContainText('40 tablet(s)');
  await shelfCard.getByRole('button', { name: 'Transfer or count' }).click();
  transferForm = page.locator('form').filter({ has: page.getByRole('button', { name: 'Dispatch stock', exact: true }) });
  await transferForm.getByRole('combobox', { name: 'Destination', exact: true }).selectOption({ label: 'Tomjoy Pharmacy shelf' });
  await transferForm.getByLabel('Dispatch quantity (tablet)').fill('10');
  await transferForm.getByLabel('Reason / delivery notes').fill('Direct shelf return to Tomjoy');
  await transferForm.getByRole('button', { name: 'Dispatch stock', exact: true }).click();
  await expect(shelfCard).toContainText('30 tablet(s)');
  await page.getByLabel('Active shop').selectOption({ label: 'Tomjoy Pharmacy' });
  await incoming.getByLabel('Actually received now (tablet)').fill('10');
  await incoming.getByLabel('Reason / delivery notes').fill('Ten returned units counted at Tomjoy');
  await incoming.getByRole('button', { name: 'Confirm receipt', exact: true }).click();
  await expect(shelfCard).toContainText('120 tablet(s)');
  await page.setViewportSize({ width: 320, height: 740 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('inventory-mobile.png'), fullPage: true });
  const secret = randomBytes(24).toString('hex');
  const staff = await page.request.post('/api/admin/users', { headers, data: { username: 'inventory.shared', name: 'Shared Storage Employee', password: secret, role: 'employee', sharedStorageAccess: true, memberships: [] } });
  expect(staff.status()).toBe(201);
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByLabel('Username', { exact: true }).fill('inventory.shared');
  await page.getByLabel('Password', { exact: true }).fill(secret);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Stock & transfers', exact: true }).click();
  const sharedLocation = page.getByRole('combobox', { name: 'Stock location', exact: true });
  await expect(sharedLocation.locator('option')).toHaveCount(2);
  await expect(sharedLocation).toHaveValue(/.+/);
  await expect(page.getByRole('button', { name: 'Receive supplier delivery' })).toBeEnabled();
});

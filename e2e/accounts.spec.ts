import { test, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';

test('administrator configures staff access and employee uses only the assigned shop on mobile', async ({ page }) => {
  const employeePassword = randomBytes(24).toString('hex');
  await page.goto('/');
  await page.getByLabel('Username', { exact: true }).fill('test.admin');
  await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByLabel('Active shop')).toHaveValue(/.+/);
  await expect(page.getByRole('heading', { name: 'Medicines & prices', exact: true })).toBeVisible();
  await page.getByLabel('Active shop').selectOption({ label: 'Joyfrimens Pharmacy' });
  await expect(page.getByRole('heading', { name: 'Medicines & prices', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await expect(page.locator('.account-permissions')).toHaveCount(0);
  await page.getByRole('button', { name: 'Staff & permissions', exact: true }).click();
  const create = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Create a staff account' }) });
  await create.getByLabel('Full name').fill('Browser Staff');
  await create.getByLabel('Username').fill('two words');
  expect(await create.getByLabel('Username').evaluate(input => (input as HTMLInputElement).validity.patternMismatch)).toBe(true);
  await create.getByLabel('Username').fill('browser-staff');
  expect(await create.getByLabel('Username').evaluate(input => (input as HTMLInputElement).validity.valid)).toBe(true);
  await create.getByLabel('Username').fill('browser.staff');
  await create.getByLabel('Initial password').fill(employeePassword);
  await create.getByLabel('Tomjoy Pharmacy', { exact: true }).check();
  await create.getByRole('button', { name: 'Create account', exact: true }).click();
  const staff = page.locator('.staff-card').filter({ has: page.getByRole('heading', { name: 'Browser Staff', exact: true }) });
  await expect(staff).toBeVisible();
  await staff.getByLabel('May change prices').first().check();
  await staff.getByRole('button', { name: 'Save permissions' }).click();
  await expect(page.getByRole('status')).toContainText('Changes saved');
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('Username', { exact: true }).fill('browser.staff');
  await page.getByLabel('Password', { exact: true }).fill(employeePassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Medicines & prices', exact: true })).toBeVisible();
  await expect(page.getByLabel('Active shop').locator('option')).toHaveCount(1);
  await expect(page.getByRole('button', { name: 'Staff & permissions', exact: true })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Shared main storage', exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Daily cash',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Start the day',exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Sales report',exact:true})).toHaveCount(0);
  await expect(page.getByText('Expected cash remaining',{exact:true})).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Medicines & prices', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await expect(page.getByRole('heading',{name:'Settings',exact:true})).toBeVisible();
  await expect(page.locator('.account-permissions')).toBeVisible();
  await expect(page.getByLabel('Current password',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Change password',exact:true}).click();
  await page.getByLabel('Current password', { exact: true }).fill(employeePassword);
  await page.getByLabel('New password', { exact: true }).fill(randomBytes(24).toString('hex'));
  await page.getByRole('button', { name: 'Save new password' }).click();
  await expect(page.getByRole('heading', { name: 'Sign in' })).toBeVisible();
  await expect(page.getByRole('alert')).toContainText('Password changed');
});

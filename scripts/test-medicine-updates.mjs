// Isolated browser regression; uses built assets and a fresh in-memory database.
import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { preview } from 'vite';
import { buildApp } from '../backend/dist/app.js';
import { openDatabase } from '../backend/dist/database.js';
import { bootstrap } from '../backend/dist/setup.js';
import { migrate } from '../backend/dist/migrate.js';
import { readConfig } from '../backend/dist/config.js';

const db = await openDatabase({ dataDir: 'memory://' });
let app, web, browser;
try {
  await migrate(db);
  const password = randomBytes(24).toString('hex');
  await bootstrap(db, { username: 'browser.admin', password, name: 'Browser Admin', shops: ['Tomjoy Pharmacy', 'Joyfrimens Pharmacy'], currency: 'GHS', timezone: 'Etc/GMT' });
  app = buildApp({ db, config: readConfig({ NODE_ENV: 'test', APP_ORIGINS: 'http://127.0.0.1:4192' }) });
  const apiAddress = await app.listen({ host: '127.0.0.1', port: 0 });
  web = await preview({ configFile: false, root: resolve('frontend'), preview: { host: '127.0.0.1', port: 4192, strictPort: true, proxy: { '/api': apiAddress } } });
  browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined });
  const page = await browser.newPage({ baseURL: 'http://127.0.0.1:4192', viewport: { width: 390, height: 844 } });
  page.setDefaultTimeout(10000);
  page.on('pageerror',e=>console.log('PAGE ERROR',e.message));
  page.on('requestfailed',r=>{if(!r.url().includes('/api/'))console.log('FAILED ASSET',r.url(),r.failure());});
  await page.goto('http://127.0.0.1:4192');
  await page.getByLabel('Username', { exact: true }).fill('browser.admin');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByLabel('Search medicines', { exact: true }).waitFor();
  const me = await (await page.request.get('/api/auth/me')).json();
  const headers = { 'x-requested-with': 'joyfrimens', 'x-csrf-token': me.csrfToken };
  const shop = (await (await page.request.get('/api/shops')).json()).shops[0];
  const drugName='=Paste, "20g"';
  const product=await page.request.post('/api/shops/'+shop.id+'/catalogue',{headers,data:{name:drugName,baseUnit:'tube',units:[{label:'tube',baseQuantity:1,barcode:'',priceMinor:1000},{label:'box',baseQuantity:10,barcode:'',priceMinor:8000}]}});assert.equal(product.status(),201);
  const products=(await(await page.request.get('/api/shops/'+shop.id+'/catalogue')).json()).products;
  const tube=products[0].units.find(u=>u.label==='tube');
  const changed=await page.request.put('/api/shops/'+shop.id+'/catalogue/units/'+tube.id+'/availability',{headers,data:{available:false,expectedVersion:1}});assert.equal(changed.status(),200);
  await page.getByRole('button',{name:'Unavailable medicines',exact:true}).click();
  await expect(page.locator('.medicine-card')).toHaveCount(1);
  await expect(page.locator('.pack-name')).toHaveText('tube');
  const downloading=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download list',exact:true}).click();
  const download=await downloading;assert.match(download.suggestedFilename(),/unavailable-medicines-Tomjoy/);
  const stream=await download.createReadStream(),chunks=[];for await(const chunk of stream)chunks.push(chunk);const csv=Buffer.concat(chunks).toString('utf8');
  assert.ok(csv.includes("'"+drugName.replaceAll('"','""')));assert.ok(csv.includes('10.00'));assert.ok(!csv.includes('80.00'));assert.ok(csv.includes('Tomjoy Pharmacy'));
  await page.setViewportSize({width:320,height:740});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'test-results/unavailable-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Account',exact:true}).click();assert.equal(await page.locator('.account-permissions').count(),0);
  const staffPassword=randomBytes(24).toString('hex');const staff=await page.request.post('/api/admin/users',{headers,data:{username:'notice.employee',password:staffPassword,name:'Notice Employee',role:'employee',memberships:[{shopId:shop.id,canChangePrices:false}],sharedStorageAccess:false}});assert.equal(staff.status(),201);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByLabel('Username',{exact:true}).fill('notice.employee');await page.getByLabel('Password',{exact:true}).fill(staffPassword);await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('button',{name:/Medicine updates/}).click();const updates=page.getByRole('dialog',{name:'Medicine updates',exact:true});
  await expect(updates.locator('.medicine-update')).toHaveCount(3);await expect(updates).toContainText('Medicine added');await expect(updates).toContainText('10.00');
  await updates.getByRole('button',{name:'Mark these updates read'}).click();await expect(updates.locator('.unread')).toHaveCount(0);
  await updates.getByRole('button',{name:'Close Medicine updates'}).click();
  const login=await app.inject({method:'POST',url:'/api/auth/login',headers:{'x-requested-with':'joyfrimens'},payload:{username:'browser.admin',password}});assert.equal(login.statusCode,200);
  const adminHeaders={'x-requested-with':'joyfrimens','x-csrf-token':login.json().csrfToken,cookie:String(login.headers['set-cookie']).split(';')[0]};
  const price=await app.inject({method:'PUT',url:'/api/shops/'+shop.id+'/catalogue/units/'+tube.id+'/price',headers:adminHeaders,payload:{priceMinor:1200,expectedVersion:1}});assert.equal(price.statusCode,200,price.body);
  await page.evaluate(()=>window.dispatchEvent(new Event('online')));
  await expect(page.getByRole('button',{name:'Medicine updates (1 unread)',exact:true})).toBeVisible();
  await page.getByRole('button',{name:/Medicine updates/}).click();await expect(updates.locator('.medicine-update').first()).toContainText('Price updated');await expect(updates.locator('.medicine-update').first()).toContainText('12.00');
  await page.screenshot({path:'test-results/medicine-updates-mobile.png',fullPage:true});
  await updates.getByRole('button',{name:'Close Medicine updates'}).click();
  await page.getByRole('button',{name:'Account',exact:true}).click();await expect(page.locator('.account-permissions')).toBeVisible();
  console.log('PASS: unavailable filter, safe CSV download, employee update notification and read state, admin/employee permissions visibility.');
} finally {await browser?.close();if(web)await new Promise(resolve=>web.httpServer.close(resolve));await app?.close();await db.close();}

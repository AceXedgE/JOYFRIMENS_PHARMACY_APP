  await moneyOut.getByRole('button',{name:'Record money out',exact:true}).click();
  await page.getByRole('button',{name:'Retry money-out entry',exact:true}).waitFor();
  await page.unroute('**/cash/money-out');await page.reload();
  await page.getByRole('button',{name:'Money out',exact:true}).click();
  await page.getByRole('button',{name:'Retry money-out entry',exact:true}).click();
  await page.getByRole('status').filter({hasText:'recorded and deducted'}).waitFor();
  assert.equal((await db.query("SELECT * FROM cash_ledger WHERE kind='expense'")).rows.length,1);
  assert.equal((await db.query('SELECT * FROM cash_requests')).rows.length,0);
  await page.getByRole('button',{name:'Daily cash',exact:true}).click();
  await sending.getByLabel('Cash left in shop (GHS)').fill('14.00');
  assert.equal(await sending.getByLabel('Money sent to').count(),0);
  assert.equal(await sending.getByLabel('Sales date').inputValue(),new Date().toISOString().slice(0,10));
  await sending.getByLabel('Sales date').fill('2001-02-03');
  await sending.getByLabel('These are the final amounts being sent and left in the shop.').check();
  await page.route('**/day/send',async route=>{const r=await route.fetch();assert.equal(r.status(),200);await route.abort('failed');});
  await sending.getByRole('button',{name:'Submit final count',exact:true}).click();
  await page.getByRole('button',{name:'Retry pending daily cash record'}).waitFor();
  await page.unroute('**/day/send');
  await page.reload();
  await page.getByRole('button',{name:'Daily cash',exact:true}).click();
  await page.getByRole('button',{name:'Retry pending daily cash record'}).click();
  await page.getByText('Difference',{exact:false}).filter({hasText:'1.00'}).waitFor();
  assert.equal((await db.query('SELECT * FROM shop_remittances')).rows.length,1);
  const dated=(await db.query('SELECT sales_date::text,created_at,recipient FROM shop_remittances')).rows[0];assert.equal(dated.sales_date,'2001-02-03');assert.equal(dated.recipient,null);assert.equal(new Date(dated.created_at).toISOString().slice(0,10),new Date().toISOString().slice(0,10));
  const record=(await db.query('SELECT expected_minor::text,left_minor FROM shop_day_closings')).rows[0];assert.deepEqual(record,{expected_minor:'1500',left_minor:1400});
  await page.setViewportSize({width:320,height:740});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'test-results/daily-cash-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Account',exact:true}).click();
  await page.screenshot({path:'test-results/account-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByLabel('Username',{exact:true}).fill('second.owner');
  await page.getByLabel('Password',{exact:true}).fill(secondPassword);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('button',{name:'Daily cash',exact:true}).click();
  const review=page.getByRole('form',{name:'Record owner review',exact:true});
  await review.getByRole('button',{name:'Record owner review',exact:true}).click();
  await page.getByText('Owner review: Closing reviewed by administrator').waitFor();
  const shops=(await (await page.request.get('/api/shops')).json()).shops;

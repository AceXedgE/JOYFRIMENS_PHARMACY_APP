  await page.getByRole('button',{name:'Start day',exact:true}).click();
  await page.getByRole('form',{name:'Record daily sales total',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:"Finish today's sales",exact:true}).isDisabled(),true);
  await page.locator('summary').filter({hasText:'Extra change brought in'}).click();
  await page.getByLabel('Extra change amount (GHS)').fill('20');
  await page.getByRole('button',{name:'Record extra change',exact:true}).click();
  await page.getByRole('button',{name:'Record extra change',exact:true}).waitFor({state:'visible'});
  await page.getByLabel('Total sales for the day (GHS)').fill('100');
  await page.getByRole('button',{name:'Record daily sales total',exact:true}).click();
  await page.getByRole('form',{name:'Record daily sales total',exact:true}).waitFor({state:'detached'});
  await page.getByRole('button',{name:'Counter',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Open ticket',exact:true}).isDisabled(),true);
  await page.getByRole('button',{name:'Daily cash',exact:true}).click();
